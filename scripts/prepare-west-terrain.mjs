// Bake walkable exterior step heights from the shipped, transformed GLB.
// Runtime uses a compact grid, not repeated raycasts against the render mesh.
import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {dequantize} from '@gltf-transform/functions';
import {MeshoptDecoder} from 'meshoptimizer';
import * as T from 'three';
import {writeFile} from 'node:fs/promises';
await MeshoptDecoder.ready;
const doc=await new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.decoder':MeshoptDecoder}).read('public/models/white-house-west-v1.glb');
await doc.transform(dequantize());
// All exterior walking surfaces: north entrance, east-west gallery and its
// south-running return beside the Rose Garden. The roof starts above 4 m;
// accept only upward surfaces below 2 m so the ceiling cannot become a floor.
const fields=[
 {x:-95,z:-29,w:151,d:111,step:.1},
 {x:-74,z:-23.5,w:491,d:81,step:.1},
 {x:-65,z:-15.5,w:81,d:266,step:.1},
].map(f=>({...f,data:new Int16Array(f.w*f.d)}));
let triangles=0;
for(const node of doc.getRoot().listNodes()){
 if(!node.getMesh())continue;const matrix=new T.Matrix4().fromArray(node.getWorldMatrix());
 for(const p of node.getMesh().listPrimitives()){
  const raw=p.getAttribute('POSITION').getArray(),ids=p.getIndices().getArray(),points=[];
  for(let i=0;i<raw.length;i+=3)points.push(new T.Vector3(raw[i],raw[i+1],raw[i+2]).applyMatrix4(matrix));
  for(let i=0;i<ids.length;i+=3){const [a,b,c]=[points[ids[i]],points[ids[i+1]],points[ids[i+2]]];
   const n=b.clone().sub(a).cross(c.clone().sub(a)).normalize();if(n.y<.65||Math.max(a.y,b.y,c.y)>2)continue;triangles++;
   const den=(b.z-c.z)*(a.x-c.x)+(c.x-b.x)*(a.z-c.z);if(Math.abs(den)<1e-8)continue;
   for(const field of fields){
    const left=Math.max(0,Math.ceil((Math.min(a.x,b.x,c.x)-field.x)/field.step)),right=Math.min(field.w-1,Math.floor((Math.max(a.x,b.x,c.x)-field.x)/field.step));
    const top=Math.max(0,Math.ceil((Math.min(a.z,b.z,c.z)-field.z)/field.step)),bottom=Math.min(field.d-1,Math.floor((Math.max(a.z,b.z,c.z)-field.z)/field.step));
    for(let j=top;j<=bottom;j++)for(let k=left;k<=right;k++){
     const x=field.x+k*field.step,z=field.z+j*field.step;
     const u=((b.z-c.z)*(x-c.x)+(c.x-b.x)*(z-c.z))/den,v=((c.z-a.z)*(x-c.x)+(a.x-c.x)*(z-c.z))/den;
     if(u>=-1e-5&&v>=-1e-5&&u+v<=1.00001){const height=Math.round((u*a.y+v*b.y+(1-u-v)*c.y)*100);field.data[j*field.w+k]=Math.max(field.data[j*field.w+k],height);}
    }
   }
  }
 }
}
const data=fields.map(({data,...field})=>{const rle=[];for(let i=0;i<data.length;){const height=data[i];let j=i+1;while(j<data.length&&data[j]===height)j++;rle.push(j-i,height);i=j;}return {...field,rle};});
await writeFile('lib/west-terrain-data.ts','// Generated by scripts/prepare-west-terrain.mjs from white-house-west-v1.glb.\nexport const WEST_TERRAIN='+JSON.stringify(data)+';\n');
console.log({upwardTriangles:triangles,samples:fields.reduce((n,f)=>n+f.data.length,0),bytes:JSON.stringify(data).length});
